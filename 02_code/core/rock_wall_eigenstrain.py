"""Rock-wall displacement produced by a committed plastic-strain field.

The exterior rock is discretised into annular sectors.  Plastic strain is
constant in Cartesian components in every sector.  Betti's reciprocal theorem
with elastic harmonic test fields gives the Fourier coefficients of the wall
displacement.  This module changes neither the Mohr--Coulomb law nor the
elastic traction compliance; it only evaluates the displacement generated by
the current plastic eigenstrain field.
"""
from __future__ import annotations

import numpy as np

from nonaxisymmetric_nonassociated_domain import rotation, transform


TENSOR_METRIC = np.array([1.0, 1.0, 1.0, 2.0])


def power_average(a: np.ndarray, b: np.ndarray, power: int) -> np.ndarray:
    """Area average of ``(r/R)**power`` over each radial interval."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    exponent = power + 2
    if exponent == 0:
        return 2.0 * np.log(b / a) / (b * b - a * a)
    return (
        2.0 * a ** exponent * np.expm1(exponent * np.log(b / a))
        / (exponent * (b * b - a * a))
    )


def radial_test_stress(n: int, a: np.ndarray, b: np.ndarray, nu: float,
                       radial_traction: float, tangential_traction: float) -> np.ndarray:
    """Radial amplitudes of the decaying elastic harmonic test field."""
    if n < 1:
        raise ValueError("The mean test field is handled explicitly")
    tr, tt = float(radial_traction), float(tangential_traction)
    if n == 1:
        kelvin = (tr - tt) / (4.0 * (1.0 - nu)) * power_average(a, b, -1)
        residual = tr - (3.0 - 2.0 * nu) * (tr - tt) / (4.0 * (1.0 - nu))
        decaying = residual * power_average(a, b, -3)
        return np.array([
            -(3.0 - 2.0 * nu) * kelvin - decaying,
            (1.0 - 2.0 * nu) * kelvin + decaying,
            (1.0 - 2.0 * nu) * kelvin - decaying,
        ]).T
    c0 = (tr - tt) / (2.0 * (n - 1.0))
    c1 = ((n + 2.0) * tt - n * tr) / (2.0 * n * (n + 1.0))
    result = np.zeros((len(a), 3))
    for exponent, coefficient in ((2 - n, c0), (-n, c1)):
        radial = coefficient * power_average(a, b, exponent - 2)
        result += radial[:, None] * np.array([
            exponent - n * n, exponent * (exponent - 1.0),
            n * (exponent - 1.0),
        ])
    return result


def angular_tensor_average(n: int, radial: np.ndarray, width: float, nu: float) -> np.ndarray:
    """Exact sector average in fixed Cartesian tensor components."""
    ar, at, ash = radial.T
    mean, deviator, shear = (ar + at) / 2.0, (ar - at) / 2.0, -1j * ash
    moment = lambda k: np.sinc(k * width / (2.0 * np.pi))
    mn = moment(n)
    cosine = (moment(n + 2) + moment(n - 2)) / 2.0
    sine = (moment(n + 2) - moment(n - 2)) / (2j)
    return np.stack([
        mean * mn + deviator * cosine - shear * sine,
        mean * mn - deviator * cosine + shear * sine,
        nu * (ar + at) * mn,
        deviator * sine + shear * cosine,
    ], axis=-1)


class RockWallEigenstrain:
    """Map cellwise plastic strain to rock-wall displacement harmonics."""

    def __init__(self, radii: np.ndarray, angular_cells: int, maximum_order: int,
                 E: float = 12.0e9, nu: float = 0.26, radius: float = 6.5):
        self.radii = np.asarray(radii, float)
        self.nt, self.order = int(angular_cells), int(maximum_order)
        self.E, self.nu, self.radius = float(E), float(nu), float(radius)
        if (self.nt < 4 or self.order < 1 or len(self.radii) < 2 or
                np.any(np.diff(self.radii) <= 0.0) or self.radii[0] < self.radius - 1.0e-12):
            raise ValueError("Invalid exterior source grid")
        self.nr = len(self.radii) - 1
        self.width = 2.0 * np.pi / self.nt
        self.angles = (np.arange(self.nt) + 0.5) * self.width
        self.into_local = np.array([transform(rotation(angle).T) for angle in self.angles])
        a, b = self.radii[:-1] / self.radius, self.radii[1:] / self.radius
        self.work = np.zeros((self.order + 1, self.nr, 2, 4), complex)
        inverse_square = power_average(a, b, -2)
        sinc = np.sinc(self.width / np.pi)
        normal = np.stack([
            -inverse_square * sinc, inverse_square * sinc,
            np.zeros(self.nr), np.zeros(self.nr),
        ], axis=-1)
        tangent = np.stack([
            np.zeros(self.nr), np.zeros(self.nr), np.zeros(self.nr),
            -inverse_square * sinc,
        ], axis=-1)
        area_factor = self.radius * (b * b - a * a) / self.nt
        self.work[0] = (
            area_factor[:, None, None] / 2.0
            * np.stack([normal, tangent], axis=1) * TENSOR_METRIC
        )
        for n in range(1, self.order + 1):
            normal = angular_tensor_average(
                n, radial_test_stress(n, a, b, self.nu, 1.0, 0.0), self.width, self.nu
            )
            tangent = 1j * angular_tensor_average(
                n, radial_test_stress(n, a, b, self.nu, 0.0, 1.0), self.width, self.nu
            )
            self.work[n] = (
                area_factor[:, None, None]
                * np.conj(np.stack([normal, tangent], axis=1)) * TENSOR_METRIC
            )

    def coefficients(self, plastic_strain: np.ndarray) -> np.ndarray:
        plastic = np.asarray(plastic_strain, float).reshape(self.nr, self.nt, 4)
        if not np.all(np.isfinite(plastic)):
            raise ValueError("Plastic strain contains nonfinite values")
        local = np.einsum("jab,rjb->rja", self.into_local, plastic)
        frequency = np.fft.fft(local, axis=1)
        orders = np.arange(self.order + 1)
        repeated = frequency[:, orders % self.nt].transpose(1, 0, 2)
        return (
            np.einsum("nroc,nrc->no", self.work, repeated, optimize=True)
            * np.exp(-1j * orders * self.width / 2.0)[:, None]
        )

